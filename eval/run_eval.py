"""Score translation quality on FLORES-200 and write eval/results.md.

    python eval/fetch_data.py
    python eval/run_eval.py --limit 100                 # quick check of all 12 pairs
    python eval/run_eval.py                             # full 1,012-sentence devtest
    python eval/run_eval.py --compare --pairs sa-en,en-sa,sa-zh,zh-sa
                                                        # try alternative models/routes per pair

Metrics: chrF++ (sacrebleu, word_order=2: the primary metric in IndicTrans2's evaluation) and
BLEU (spBLEU `flores200` tokenizer, or `zh` for Chinese). Numbers come only from real runs of the
models in this repo; nothing in results.md is typed by hand. IndicTrans2 runs are strict: no
silent fallback to NLLB, so a score always belongs to the model named next to it.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import platform
import sys
import time
from dataclasses import asdict, dataclass
from pathlib import Path

HERE = Path(__file__).parent
FLORES = {"sa": "san_Deva", "hi": "hin_Deva", "en": "eng_Latn", "zh": "zho_Hans"}


@dataclass
class PairResult:
    src: str
    tgt: str
    variant: str  # "(default)", "nllb", "opus", "direct", "pivot"
    via: str
    route: str
    chrf_pp: float
    bleu: float
    n: int
    seconds: float


def load_flores(data_dir: Path, split: str, lang: str, limit: int | None) -> list[str]:
    path = data_dir / split / f"{FLORES[lang]}.{split}"
    if not path.is_file():
        raise SystemExit(f"{path} not found. Run: python eval/fetch_data.py")
    lines = path.read_text(encoding="utf8").splitlines()
    return lines[:limit] if limit else lines


def score(hyps: list[str], refs: list[str], tgt: str) -> tuple[float, float, str, str]:
    from sacrebleu.metrics import BLEU, CHRF

    chrf = CHRF(word_order=2)
    tokenize = "zh" if tgt == "zh" else "flores200"
    try:
        bleu = BLEU(tokenize=tokenize)
        bleu_score = bleu.corpus_score(hyps, [refs])
    except Exception as exc:  # flores200 needs a one-time SPM download; fall back loudly
        print(
            f"  note: tokenizer {tokenize!r} unavailable ({exc}); using 13a for BLEU",
            file=sys.stderr,
        )
        bleu = BLEU(tokenize="13a")
        bleu_score = bleu.corpus_score(hyps, [refs])
    chrf_score = chrf.corpus_score(hyps, [refs])
    return chrf_score.score, bleu_score.score, str(chrf.get_signature()), str(bleu.get_signature())


def candidates(router, src: str, tgt: str, compare: bool) -> list[str]:
    """Route overrides to evaluate for a pair; '(default)' means no override."""
    out = ["(default)"]
    if not compare:
        return out
    default = router.plan(src, tgt)
    default_backends = {h.backend for h in default}
    if (
        "nllb" in router.backends
        and "nllb" not in default_backends
        and router.backends["nllb"].supports(src, tgt)
    ):
        out.append("nllb")
    if "opus" in router.backends and router.backends["opus"].supports(src, tgt):
        out.append("opus")
    if "zh" in (src, tgt) and "en" not in (src, tgt):
        out.append("direct" if len(default) == 2 else "pivot")
    return out


def evaluate_pair(router, src: str, tgt: str, srcs: list[str], refs: list[str], variant: str):
    from lingua_bridge.translate.router import Router

    r = router if variant == "(default)" else Router(
        router.backends, {**router.overrides, f"{src}>{tgt}": variant}, preference=router.preference,
        pivot_by_default=router.pivot_by_default, fallback_to_nllb=False)  # fmt: skip
    t0 = time.perf_counter()
    res = r.translate(srcs, src, tgt)
    seconds = time.perf_counter() - t0
    chrf, bleu, chrf_sig, bleu_sig = score(res.texts, refs, tgt)
    route = (
        " → ".join(f"{h.src}→{h.tgt} `{h.model.split('/')[-1]}`" for h in res.hops) or "identity"
    )
    return (
        PairResult(
            src,
            tgt,
            variant,
            res.via,
            route,
            round(chrf, 1),
            round(bleu, 1),
            len(srcs),
            round(seconds, 1),
        ),
        chrf_sig,
        bleu_sig,
        res.texts,
    )


def render_markdown(
    results: list[PairResult], meta: dict, sigs: tuple[str, str], best: dict
) -> str:
    lines = [
        "# Evaluation results",
        "",
        f"Generated by `eval/run_eval.py` on {meta['date']}. Every number below comes from that run; nothing is hand-edited.",
        "",
        f"- Benchmark: FLORES-200 `{meta['split']}`, {meta['n']} sentences per pair, translating from the human source side to the human target side",
        f"- Model profile: `{meta['profile']}` · device: {meta['device']} · beams: {meta['beams']} · dtype: {meta['dtype']}",
        "- chrF++ is the primary metric (higher is better, 0 to 100). BLEU is spBLEU (`flores200` tokenizer; `zh` tokenizer for Chinese targets).",
        "",
        "| Pair | Variant | Route | chrF++ | BLEU | Time (s) |",
        "|---|---|---|---:|---:|---:|",
    ]
    compared = {
        (r.src, r.tgt)
        for r in results
        if sum((x.src, x.tgt) == (r.src, r.tgt) for x in results) > 1
    }
    for r in sorted(results, key=lambda r: (r.src, r.tgt, r.variant)):
        star = " ★" if (r.src, r.tgt) in compared and best.get((r.src, r.tgt)) == r.variant else ""
        lines.append(
            f"| {r.src} → {r.tgt} | {r.variant}{star} | {r.route} ({r.via}) | {r.chrf_pp:.1f} | {r.bleu:.1f} | {r.seconds:.0f} |"
        )
    lines += ["", "★ = best chrF++ among the variants compared for that pair.", ""]
    overrides = {f"{s}>{t}": v for (s, t), v in best.items() if v != "(default)"}
    if overrides:
        lines += [
            "Variants that beat the default on chrF++ (set to adopt them):",
            "",
            "```",
            f"LB_ROUTE_OVERRIDES='{json.dumps(overrides)}'",
            "```",
            "",
        ]
    lines += [
        "## Reproducibility",
        "",
        f"- sacrebleu chrF++ signature: `{sigs[0]}`",
        f"- sacrebleu BLEU signature: `{sigs[1]}`",
        f"- Python {platform.python_version()} on {platform.system()}",
        "",
        "## Reading these numbers",
        "",
        "- Sentence-level FLORES text is Wikipedia-style prose. Scores say little about chat, legal or technical text.",
        "- Pivot routes (two hops) translate text that already contains the first hop's mistakes.",
        "- Sanskrit references are single human translations; free word order and sandhi mean a correct translation can still score low.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument(
        "--pairs", default="all", help="comma list like sa-en,hi-zh, or 'all' (12 pairs)"
    )
    ap.add_argument("--limit", type=int, default=0, help="first N sentences only (0 = all 1,012)")
    ap.add_argument("--split", default="devtest", choices=["dev", "devtest"])
    ap.add_argument("--profile", choices=["small", "base"], default=None)
    ap.add_argument(
        "--compare", action="store_true", help="also evaluate alternative models/routes per pair"
    )
    ap.add_argument("--data-dir", type=Path, default=HERE / "data" / "flores200")
    ap.add_argument("--out", type=Path, default=HERE / "results.md")
    args = ap.parse_args(argv)

    from lingua_bridge.config import Settings
    from lingua_bridge.engine import LinguaBridge
    from lingua_bridge.languages import all_pairs
    from lingua_bridge.translate.base import resolve_device

    overrides = {"fallback_to_nllb": False}  # strict: a score must belong to the model it names
    if args.profile:
        overrides["profile"] = args.profile
    settings = Settings(**overrides)
    engine = LinguaBridge(settings)
    pairs = (
        all_pairs() if args.pairs == "all" else [tuple(p.split("-")) for p in args.pairs.split(",")]
    )
    try:
        device = resolve_device(settings)
    except Exception:
        device = "unknown"

    results: list[PairResult] = []
    sigs = ("", "")
    for src, tgt in pairs:
        srcs = load_flores(args.data_dir, args.split, src, args.limit or None)
        refs = load_flores(args.data_dir, args.split, tgt, args.limit or None)
        for variant in candidates(engine.router, src, tgt, args.compare):
            print(f"{src}->{tgt} [{variant}] on {len(srcs)} sentences ...", flush=True)
            r, *sig, _ = evaluate_pair(engine.router, src, tgt, srcs, refs, variant)
            sigs = (sig[0], sig[1])
            results.append(r)
            print(
                f"  chrF++ {r.chrf_pp:.1f}  BLEU {r.bleu:.1f}  ({r.seconds:.0f}s)  {r.route}",
                flush=True,
            )

    best: dict[tuple[str, str], str] = {}
    top: dict[tuple[str, str], float] = {}
    for r in results:
        key = (r.src, r.tgt)
        if r.chrf_pp > top.get(key, -1.0):
            best[key], top[key] = r.variant, r.chrf_pp
    meta = {"date": dt.date.today().isoformat(), "split": args.split, "n": results[0].n if results else 0,
            "profile": settings.profile, "device": device, "beams": settings.num_beams, "dtype": settings.dtype}  # fmt: skip
    args.out.write_text(render_markdown(results, meta, sigs, best), encoding="utf8")
    args.out.with_suffix(".json").write_text(
        json.dumps(
            {"meta": meta, "results": [asdict(r) for r in results]}, indent=1, ensure_ascii=False
        ),
        encoding="utf8",
    )
    print(f"\nWrote {args.out}")


if __name__ == "__main__":
    main()
